fn inRanges(ranges: []const CodepointRange, cp: u21) bool {
    var lo: usize = 0;
    var hi: usize = ranges.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        const r = ranges[mid];
        if (cp < r.lo) {
            hi = mid;
        } else if (cp > r.hi) {
            lo = mid + 1;
        } else {
            return true;
        }
    }
    return false;
}

/// Lowercases a single codepoint using the simple (one-to-one) Unicode
/// mapping. Codepoints without such a mapping are returned unchanged.
pub fn toLower(cp: u21) u21 {
    if (cp < 0x80) return std.ascii.toLower(@intCast(cp));

    var lo: usize = 0;
    var hi: usize = lower_ranges.len;
    while (lo < hi) {
        const mid = lo + (hi - lo) / 2;
        const r = lower_ranges[mid];
        if (cp < r.lo) {
            hi = mid;
        } else if (cp > r.hi) {
            lo = mid + 1;
        } else {
            return @intCast(@as(i32, cp) + r.delta);
        }
    }
    return cp;
}

/// Returns true for the Unicode `Case_Ignorable` property.
pub fn isCaseIgnorable(cp: u21) bool {
    if (cp < 0x80) return cp == '\'' or cp == '.' or cp == ':' or cp == '^' or cp == '`';
    return inRanges(&case_ignorable_ranges, cp);
}

/// Returns true for the Unicode `Cased` property.
pub fn isCased(cp: u21) bool {
    if (cp < 0x80) return (cp >= 'A' and cp <= 'Z') or (cp >= 'a' and cp <= 'z');
    return inRanges(&cased_ranges, cp);
}
